# Este programa demonstra como receber entrada de dados do usuário
# A função input() permite que o programa receba informações digitadas pelo usuário

# Solicita ao usuário que digite seu nome e armazena na variável nome_usuario
# O programa aguarda o usuário digitar e pressionar Enter
nome_usuario = input('Digite seu nome?: ')

# Exibe uma mensagem personalizada usando o nome informado pelo usuário
print (f'Olá, {nome_usuario}! Seja bem-vindo ao nosso sistema!')