# Este programa demonstra o uso de variáveis em Python
# Variáveis são espaços na memória que armazenam valores

# Definindo variáveis com valores iniciais
nome = 'Joãozin'  # Variável do tipo string (texto)
idade = 10  # Variável do tipo inteiro (número)

# Exibindo as variáveis diretamente, separadas por espaço
print(nome, idade)

# Exibindo as variáveis usando f-string (formatação de strings)
# A f-string permite inserir variáveis dentro de textos de forma mais legível
print(f'Nome: {nome} Idade: {idade}')