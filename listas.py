# Este programa demonstra o uso de listas em Python
# Listas são coleções ordenadas de itens, que podem ser de qualquer tipo

# Criando uma lista de strings (textos) para representar uma lista de compras
lista_de_compras = ['arroz', 'feijão', 'carne', 'leite', 'ovos']

# Criando uma lista de números inteiros
numeros_da_sorte = [1, 2, 3, 4, 5]

# Loop for (para) percorre cada item da lista
# Para cada item na lista_de_compras, executa o código dentro do bloco
for item in lista_de_compras:
    # Exibe cada item da lista
    print(item)

# O mesmo loop for pode ser usado com qualquer lista
# Percorre cada número da lista numeros_da_sorte
for item in numeros_da_sorte:
    # Exibe cada número da lista
    print(item)