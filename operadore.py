# Este programa demonstra o uso de operadores aritméticos em Python
# Operadores aritméticos realizam cálculos matemáticos

# Operadores aritméticos básicos
print(10 + 10)  # Adição: soma dois números
print(25 - 10)  # Subtração: subtrai um número do outro
print(10 * 10)  # Multiplicação: multiplica dois números
print(100 / 10)  # Divisão: divide um número pelo outro


# Operadores de comparação e lógicos:
# Operadores de comparação retornam True (verdadeiro) ou False (falso)
print(10 > 5)   # Maior que: verifica se 10 é maior que 5
print(10 < 5)   # Menor que: verifica se 10 é menor que 5
print(10 == 10) # Igual a: verifica se os valores são iguais
print(10 != 10) # Diferente de: verifica se os valores são diferentes
print(10 >= 10) # Maior ou igual a: verifica se é maior ou igual
print(10 <= 10) # Menor ou igual a: verifica se é menor ou igual

# Operadores lógicos trabalham com valores booleanos (True/False)
print(10 and 5) # AND: retorna o último valor se ambos forem verdadeiros
print(10 or 5)  # OR: retorna o primeiro valor verdadeiro encontrado
print(not 10)   # NOT: inverte o valor booleano (10 é True, not True = False)
print(not 0)    # NOT: zero é False, not False = True